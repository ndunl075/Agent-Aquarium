import { spawn } from 'node:child_process';
import { build } from 'esbuild';
import { createServer } from 'vite';
import { resolve } from 'node:path';
const alias = Object.fromEntries(['protocol','domain','adapters','cli'].map(name => [`@aquarium/${name}`, resolve(`packages/${name}/src/index.ts`)]));
for (const [entry,outfile] of [['apps/desktop/src/main/index.ts','main.cjs'],['apps/desktop/src/preload/index.ts','preload.cjs'],['packages/cli/src/bin.ts','cli.cjs']]) await build({entryPoints:[entry],outfile:`apps/desktop/dist/${outfile}`,bundle:true,platform:'node',format:'cjs',external:['electron','better-sqlite3'],alias});
const server = await createServer({root:'apps/desktop',resolve:{alias},server:{host:'127.0.0.1'}});
await server.listen();
const electron = spawn(process.platform==='win32'?'node_modules/.bin/electron.cmd':'node_modules/.bin/electron',['apps/desktop/dist/main.cjs'],{stdio:'inherit',shell:process.platform==='win32',env:{...process.env,AQUARIUM_DEV_URL:server.resolvedUrls.local[0]}});
electron.on('exit',async code=>{await server.close();process.exit(code??0);});

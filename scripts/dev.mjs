import { spawn } from 'node:child_process';
import { build } from 'esbuild';
import { createServer } from 'vite';
import { resolve } from 'node:path';
import { mkdir,copyFile } from 'node:fs/promises';
import { ensureElectronNative } from './native.mjs';
import electronPath from 'electron';
import { prepareCompanion } from './companion.mjs';
await ensureElectronNative();
await mkdir('apps/desktop/dist',{recursive:true});
await copyFile('assets/aquarium.png','apps/desktop/dist/icon.png');
const alias = Object.fromEntries(['protocol','domain','adapters','cli'].map(name => [`@aquarium/${name}`, resolve(`packages/${name}/src/index.ts`)]));
await prepareCompanion();
for (const [entry,outfile] of [['apps/desktop/src/main/index.ts','main.cjs'],['apps/desktop/src/preload/index.ts','preload.cjs'],['packages/cli/src/bin.ts','cli/bin.cjs']]) await build({entryPoints:[entry],outfile:`apps/desktop/dist/${outfile}`,bundle:true,platform:'node',format:'cjs',external:['electron','better-sqlite3'],alias});
const server = await createServer({root:'apps/desktop',resolve:{alias},server:{host:'127.0.0.1'}});
await server.listen();
const electron = spawn(electronPath,['apps/desktop/dist/main.cjs'],{stdio:'inherit',windowsHide:true,env:{...process.env,AQUARIUM_DEV_URL:server.resolvedUrls.local[0]}});
electron.on('exit',async code=>{await server.close();process.exit(code??0);});
